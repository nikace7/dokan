"""Canonical machine-readable API error codes.

The OpenAPI contract exposes this tuple as an enum.  Keep codes stable: clients
may branch on them, while human-readable messages may change or be translated.
"""

import re


def canonical_error_code(value: str) -> str:
    """Normalize framework and domain codes to upper snake case."""
    with_word_boundaries = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", value)
    with_acronym_boundaries = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", with_word_boundaries)
    return re.sub(r"[^A-Za-z0-9]+", "_", with_acronym_boundaries).strip("_").upper()


