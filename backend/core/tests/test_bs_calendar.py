"""Tests for core/calendar/bs.py — the only BS conversion module.

The small set of known pairs below is supplemented by the golden fixture
(~500 pairs, ``fixtures/bs_golden.json``, generated by
``scripts/generate_bs_golden.py``), which pins the conversion table against
library upgrades. Both backend and frontend test against the same fixture.
"""

import json
from datetime import date
from pathlib import Path

import pytest

from core.calendar.bs import (
    SUPPORTED_RANGE_BS,
    OutOfRangeError,
    ad_to_bs,
    bs_to_ad,
    fiscal_year_bs,
    today_bs,
)

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "bs_golden.json"

# Verified against nepali-datetime 1.x conversion tables.
KNOWN_PAIRS = [
    (date(2000, 1, 1), "2056-09-17"),
    (date(2025, 7, 27), "2082-04-11"),
    (date(2026, 7, 27), "2083-04-11"),
]


@pytest.mark.parametrize(("ad", "bs"), KNOWN_PAIRS)
def test_known_pairs(ad: date, bs: str) -> None:
    assert ad_to_bs(ad) == bs
    assert bs_to_ad(bs) == ad


def test_zero_padding() -> None:
    """BS strings are always zero-padded char(10) so they sort lexically."""
    rendered = ad_to_bs(date(2025, 7, 27))
    assert len(rendered) == 10
    assert rendered == "2082-04-11"


def test_round_trip_over_supported_range() -> None:
    """A spread of dates across the table converts AD → BS → AD losslessly."""
    sample = [date(y, m, 1) for y in range(1920, 2044, 7) for m in range(1, 13, 3)]
    for ad in sample:
        assert bs_to_ad(ad_to_bs(ad)) == ad


def test_bs_to_ad_rejects_malformed_input() -> None:
    with pytest.raises(ValueError, match="zero-padded"):
        bs_to_ad("2082/04/12")
    with pytest.raises(ValueError, match="zero-padded"):
        bs_to_ad("82-4-12")


def test_out_of_range_raises() -> None:
    lo, hi = SUPPORTED_RANGE_BS
    below = date(bs_to_ad(f"{lo[0]}-{lo[1]:02d}-{lo[2]:02d}").year - 1, 1, 1)
    with pytest.raises(OutOfRangeError):
        ad_to_bs(below)
    with pytest.raises(OutOfRangeError):
        bs_to_ad(f"{hi[0] + 1}-01-01")


# --- Fiscal year (Shrawan 1 → Ashad end) ------------------------------------

# Verified against nepali-datetime 1.x: Shrawan 1, 2082 = AD 2025-07-17;
# Ashad 2082 has 32 days, so FY 2082-83 runs 2025-07-17 .. 2026-07-16.
FY_CASES = [
    (date(2025, 7, 17), "2082-83"),  # Shrawan 1, 2082 — first day of FY
    (date(2026, 7, 16), "2082-83"),  # Ashad 32, 2082 — last day of FY
    (date(2026, 7, 17), "2083-84"),  # Shrawan 1, 2083 — next FY
    (date(2025, 7, 16), "2081-82"),  # day before FY start
    (date(2025, 12, 31), "2082-83"),  # mid-year stays in the same FY
]


@pytest.mark.parametrize(("ad", "fy"), FY_CASES)
def test_fiscal_year_boundaries(ad: date, fy: str) -> None:
    assert fiscal_year_bs(ad) == fy


def test_fiscal_year_format() -> None:
    fy = fiscal_year_bs(date(2025, 10, 1))
    assert len(fy) == 7
    assert fy[4] == "-"


def test_today_bs_is_a_valid_bs_string() -> None:
    rendered = today_bs()
    assert bs_to_ad(rendered) is not None  # round-trips through the parser


# --- Golden fixture ----------------------------------------------------------


@pytest.mark.skipif(not FIXTURE_PATH.exists(), reason="golden fixture not generated yet")
def test_golden_fixture_pairs() -> None:
    """Every pair in the shared golden fixture must convert exactly."""
    pairs = json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))
    assert len(pairs) >= 500
    for pair in pairs:
        ad = date.fromisoformat(pair["ad"])
        assert ad_to_bs(ad) == pair["bs"]
        assert bs_to_ad(pair["bs"]) == ad
